const DICTS: Record<Lang, Partial<Record<Key, string>>> = { en, hi, gu };

/** Keys a language is missing, for the test that keeps translations complete. */
export function missingKeys(lang: Lang): Key[] {
  return (Object.keys(en) as Key[]).filter((k) => !DICTS[lang][k]);
}

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const text = DICTS[lang]?.[key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  return translate(getSettings().language ?? 'en', key, vars);
}

/** Re-renders when the language changes. */
export function useT(): typeof t {
  useSettings();
  return t;
}
